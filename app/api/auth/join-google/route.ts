import { NextResponse } from "next/server";
import {
  DEVICE_INVITE_COOKIE,
  DEVICE_INVITE_MAX_AGE_SECONDS,
  JOIN_FROM_COOKIE,
  readJoinFrom,
  startJoinGoogle,
} from "@/lib/content/joinLink";
import { isSupabaseConfigured } from "@/lib/server/env/supabase";
import { withApiGuard } from "@/lib/server/security/guard";
import { lookupJoinLink } from "@/lib/server/study/lookupJoinLink";
import { createStudyServerClient } from "@/lib/server/study/serverClient";

const COOKIE_MAX_AGE_SECONDS = 60 * 60 * 12;

export const POST = withApiGuard(async (request) => {
  if (!isSupabaseConfigured()) {
    return NextResponse.json({ reason: "not_configured" });
  }

  const body = (await request.json().catch(() => null)) as { from?: unknown } | null;
  const from =
    typeof body?.from === "string"
      ? readJoinFrom(`?from=${encodeURIComponent(body.from)}`)
      : null;
  const origin = new URL(request.url).origin;

  // Start OAuth from the same cookie-bound client that /auth/callback later
  // uses to exchange the code, so the PKCE code_verifier survives as a
  // cookie instead of being generated by a stateless client and lost.
  const supabase = await createStudyServerClient();
  const result = await startJoinGoogle({
    from,
    origin,
    lookup: lookupJoinLink,
    createOAuthUrl: async (redirectTo) => {
      if (!supabase) return null;
      // Forget the leftover session in this browser first. Otherwise the
      // callback can keep the earlier Google account and /consent shows
      // that user even after a new join-link click.
      await supabase.auth.signOut({ scope: "local" });
      const { data, error } = await supabase.auth.signInWithOAuth({
        provider: "google",
        options: {
          redirectTo,
          skipBrowserRedirect: true,
          // Force Google's account chooser every time. Without this,
          // Google silently reuses whichever account is already active in
          // the browser, so a snowballing classmate can land in someone
          // else's already-signed-in Google session.
          queryParams: { prompt: "select_account" },
        },
      });
      if (error) return null;
      return data.url ?? null;
    },
  });

  const response = NextResponse.json(result);
  if ("url" in result && from) {
    response.cookies.set(JOIN_FROM_COOKIE, from, {
      httpOnly: true,
      sameSite: "lax",
      secure: process.env.NODE_ENV === "production",
      path: "/",
      maxAge: COOKIE_MAX_AGE_SECONDS,
    });
  }
  if (from) {
    // Remember this device's invite past sign-out so the next tester can join.
    response.cookies.set(DEVICE_INVITE_COOKIE, from, {
      httpOnly: true,
      sameSite: "lax",
      secure: process.env.NODE_ENV === "production",
      path: "/",
      maxAge: DEVICE_INVITE_MAX_AGE_SECONDS,
    });
  }
  return response;
}, "auth");
